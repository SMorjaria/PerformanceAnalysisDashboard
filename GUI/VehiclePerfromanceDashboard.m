% ENGINEERING INTERPRETATION LOGIC
% ============================================================
    function updateEngineeringInterpretation( ...
        KPI, BaseKPI, Status, BaseStatus, CurrentOperating, ...
        frontMinimumRH, rearMinimumRH)
        % Engineering significance thresholds. These prevent numerical
        % noise from being described as a meaningful setup effect.
        downforceThresholdN    = 10;      % [N]
        efficiencyThresholdPct = 0.10;    % [%]
        balanceThreshold       = 0.001;   % [deg/g]
        marginThresholdMm      = 0.10;    % [mm]
        currentFrontMargin = KPI.frontRideHeight - frontMinimumRH;
        currentRearMargin  = KPI.rearRideHeight  - rearMinimumRH;
        baseFrontMargin    = BaseKPI.frontRideHeight - frontMinimumRH;
        baseRearMargin     = BaseKPI.rearRideHeight  - rearMinimumRH;
        currentMinMargin = min(currentFrontMargin,currentRearMargin);
        baseMinMargin    = min(baseFrontMargin,baseRearMargin);
        marginChange     = currentMinMargin - baseMinMargin;
        % PLATFORM
        if ~BaseStatus.aeroMapValid && Status.aeroMapValid
            if baseRearMargin < 0 && currentRearMargin >= 0
                platformText = sprintf( ...
                    'Rear platform brought inside aero-map range. Minimum current margin: %+.3f mm.', ...
                    currentMinMargin);
            elseif baseFrontMargin < 0 && currentFrontMargin >= 0
                platformText = sprintf( ...
                    'Front platform brought inside aero-map range. Minimum current margin: %+.3f mm.', ...
                    currentMinMargin);
            else
                platformText = sprintf( ...
                    'Platform brought inside aero-map range. Minimum current margin: %+.3f mm.', ...
                    currentMinMargin);
            end
        elseif BaseStatus.aeroMapValid && ~Status.aeroMapValid
            platformText = sprintf( ...
                'Current setup moves outside the aero-map range. Minimum margin: %+.3f mm.', ...
                currentMinMargin);
        elseif Status.aeroMapValid
            if marginChange > marginThresholdMm
                platformText = sprintf( ...
                    'Aero-platform margin improved by %+.3f mm; minimum current margin is %+.3f mm.', ...
                    marginChange,currentMinMargin);
            elseif marginChange < -marginThresholdMm
                platformText = sprintf( ...
                    'Aero-platform margin reduced by %.3f mm; minimum current margin is %+.3f mm.', ...
                    abs(marginChange),currentMinMargin);
            else
                platformText = sprintf( ...
                    'Aero-platform margin essentially unchanged; minimum current margin is %+.3f mm.', ...
                    currentMinMargin);
            end
        else
            platformText = sprintf( ...
                'Platform remains outside the aero-map range. Minimum current margin: %+.3f mm.', ...
                currentMinMargin);
        end
        % AERO
        deltaDF = KPI.downforce - BaseKPI.downforce;
        if abs(BaseKPI.downforce) > eps
            deltaDFPct = 100 * deltaDF / BaseKPI.downforce;
        else
            deltaDFPct = NaN;
        end
        if abs(BaseKPI.aeroEfficiency) > eps
            deltaEffPct = 100 * ...
                (KPI.aeroEfficiency - BaseKPI.aeroEfficiency) / ...
                BaseKPI.aeroEfficiency;
        else
            deltaEffPct = NaN;
        end
        if abs(deltaDF) >= downforceThresholdN
            if deltaDF > 0
                dfPhrase = sprintf('Downforce +%.1f N (+%.2f%%)',deltaDF,deltaDFPct);
            else
                dfPhrase = sprintf('Downforce %.1f N (%.2f%%)',deltaDF,deltaDFPct);
            end
        else
            dfPhrase = 'Downforce essentially unchanged';
        end
        if isfinite(deltaEffPct) && abs(deltaEffPct) >= efficiencyThresholdPct
            if deltaEffPct > 0
                effPhrase = sprintf('aero efficiency +%.2f%%',deltaEffPct);
            else
                effPhrase = sprintf('aero efficiency %.2f%%',deltaEffPct);
            end
        else
            effPhrase = 'aero efficiency essentially unchanged';
        end
        aeroText = sprintf('%s; %s.',dfPhrase,effPhrase);
        % BALANCE
        deltaKus = KPI.understeerGradient - BaseKPI.understeerGradient;
        if abs(deltaKus) < balanceThreshold
            balanceText = sprintf( ...
                'Lateral balance essentially unchanged. ΔKus = %+.4f deg/g.', ...
                deltaKus);
        elseif deltaKus > 0
            balanceText = sprintf( ...
                'Balance shifts toward understeer. ΔKus = %+.4f deg/g.', ...
                deltaKus);
        else
            balanceText = sprintf( ...
                'Balance shifts toward oversteer. ΔKus = %+.4f deg/g.', ...
                deltaKus);
        end
        % ASSESSMENT
        speedKmh = CurrentOperating.speed * 3.6;
        if Status.allValid
            assessmentText = sprintf( ...
                'Current setup satisfies all model validity checks at %.0f km/h.', ...
                speedKmh);
            assessmentInterpretation.FontColor = Colours.pass;
        else
            issues = {};
            if ~Status.aeroMapValid
                currentFrontMargin = KPI.frontRideHeight - frontMinimumRH;
                currentRearMargin  = KPI.rearRideHeight - rearMinimumRH;
                if currentFrontMargin < 0 && currentRearMargin < 0
                    issues{end+1} = 'front and rear aero-platform limits'; %#ok<AGROW>
                elseif currentFrontMargin < 0
                    issues{end+1} = 'front aero-platform limit'; %#ok<AGROW>
                elseif currentRearMargin < 0
                    issues{end+1} = 'rear aero-platform limit'; %#ok<AGROW>
                else
                    issues{end+1} = 'aero-platform range'; %#ok<AGROW>
                end
            end
            if ~Status.platformConverged
                issues{end+1} = 'platform convergence'; %#ok<AGROW>
            end
            if ~Status.lateralSolverConverged
                issues{end+1} = 'lateral convergence'; %#ok<AGROW>
            end
            if ~Status.verticalLoadValid
                issues{end+1} = 'vertical-load check'; %#ok<AGROW>
            end
            if isempty(issues)
                issueText = 'model status';
            else
                issueText = strjoin(issues,', ');
            end
            assessmentText = sprintf( ...
                'Current setup requires review at %.0f km/h: %s.', ...
                speedKmh,issueText);
            assessmentInterpretation.FontColor = Colours.warning;
        end
        platformInterpretation.Text = platformText;
        aeroInterpretation.Text = aeroText;
        balanceInterpretation.Text = balanceText;
        assessmentInterpretation.Text = assessmentText;
    end
