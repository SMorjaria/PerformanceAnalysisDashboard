% UPDATE TRADE-OFF MAP
% ============================================================
    function updateTradeoffMap( ...
        CurrentSetup, ...
        CurrentOperating)
        currentSpeedKmh = ...
            CurrentOperating.speed * 3.6;
        %% ----------------------------------------------------
        % CALCULATE / REFRESH TRADE-OFF STUDY
        %
        % The full spring grid is recalculated ONLY when
        % vehicle speed changes.
        %
        % Changing spring values simply moves the current
        % setup marker across the existing cached map.
        % -----------------------------------------------------
        if isempty(CachedTradeoffStudy) || ...
                abs(currentSpeedKmh - CachedTradeoffSpeed) > 1e-9
            modelStateLabel.Text = ...
                'CALCULATING TRADE-OFF MAP...';
            modelStateLabel.FontColor = ...
                Colours.warning;
            drawnow;
            CachedTradeoffStudy = ...
                springTradeoffMap( ...
                Vehicle, ...
                BaselineSetup, ...
                CurrentOperating, ...
                Tyre, ...
                Constants, ...
                AeroMap, ...
                frontSpringValues, ...
                rearSpringValues);
            CachedTradeoffSpeed = ...
                currentSpeedKmh;
        end
        Study = CachedTradeoffStudy;
        %% ----------------------------------------------------
        % EXTRACT GRID DATA
        % -----------------------------------------------------
        X = Study.FrontSpringGrid;
        Y = Study.RearSpringGrid;
        Z = Study.Results.downforce;
        Valid = ...
            logical(Study.Results.allValid);
        %% ----------------------------------------------------
        % CLEAR AXES
        % -----------------------------------------------------
        cla(analysisAxes);
        hold(analysisAxes,'on');
        %% ----------------------------------------------------
        % DETERMINE CLEAN DOWNFORCE CONTOUR LEVELS
        %
        % Use sensible 100 N engineering intervals instead of
        % MATLAB-generated values such as 7690.4586 N.
        % -----------------------------------------------------
        finiteDownforce = ...
            Z(isfinite(Z));
        minDownforce = ...
            min(finiteDownforce);
        maxDownforce = ...
            max(finiteDownforce);
        contourMin = ...
            floor(minDownforce / 100) * 100;
        contourMax = ...
            ceil(maxDownforce / 100) * 100;
        contourLevels = ...
            contourMin : 100 : contourMax;
        % Safety fallback if the range becomes very small
        if numel(contourLevels) < 3
            contourLevels = ...
                linspace( ...
                minDownforce, ...
                maxDownforce, ...
                5);
        end
        %% ----------------------------------------------------
        % FILLED DOWNFORCE MAP
        % -----------------------------------------------------
        contourf( ...
            analysisAxes, ...
            X, ...
            Y, ...
            Z, ...
            contourLevels, ...
            'LineStyle', ...
            'none');
        %% ----------------------------------------------------
        % COLOUR BAR
        % -----------------------------------------------------
        cb = ...
            colorbar(analysisAxes);
        cb.Label.String = ...
            'Downforce [N]';
        %% ----------------------------------------------------
        % DOWNFORCE CONTOUR LINES
        % -----------------------------------------------------
        [C,hContours] = ...
            contour( ...
            analysisAxes, ...
            X, ...
            Y, ...
            Z, ...
            contourLevels, ...
            'LineColor', ...
            [0.20 0.20 0.20], ...
            'LineWidth', ...
            0.8);
        %% ----------------------------------------------------
        % CLEAN CONTOUR LABELS
        %
        % Contour levels are already rounded to 100 N, so the
        % displayed labels become:
        %
        % 7200
        % 7300
        % 7400
        % ...
        %
        % rather than long decimal values.
        % -----------------------------------------------------
        clabel( ...
            C, ...
            hContours, ...
            'FontSize', ...
            8, ...
            'Color', ...
            [0.15 0.15 0.15], ...
            'LabelSpacing', ...
            650);
        %% ----------------------------------------------------
        % AERO-PLATFORM VALIDITY BOUNDARY
        %
        % allValid:
        %
        %       0 = invalid
        %       1 = valid
        %
        % The 0.5 contour therefore identifies the boundary
        % between the two regions.
        % -----------------------------------------------------
        contour( ...
            analysisAxes, ...
            X, ...
            Y, ...
            double(Valid), ...
            [0.5 0.5], ...
            'LineColor', ...
            [0 0 0], ...
            'LineWidth', ...
            3.0);
        %% ----------------------------------------------------
        % BASELINE SETUP
        % -----------------------------------------------------
        plot( ...
            analysisAxes, ...
            BaselineSetup.springFront, ...
            BaselineSetup.springRear, ...
            'x', ...
            'MarkerSize', ...
            13, ...
            'LineWidth', ...
            2.5, ...
            'Color', ...
            Colours.accent);
        text( ...
            analysisAxes, ...
            BaselineSetup.springFront + 3, ...
            BaselineSetup.springRear, ...
            'Baseline', ...
            'FontSize', ...
            9, ...
            'FontWeight', ...
            'bold', ...
            'Color', ...
            Colours.text);
        %% ----------------------------------------------------
        % CURRENT SETUP
        % -----------------------------------------------------
        plot( ...
            analysisAxes, ...
            CurrentSetup.springFront, ...
            CurrentSetup.springRear, ...
            'o', ...
            'MarkerSize', ...
            10, ...
            'LineWidth', ...
            2.5, ...
            'Color', ...
            Colours.warning);
        text( ...
            analysisAxes, ...
            CurrentSetup.springFront + 3, ...
            CurrentSetup.springRear, ...
            'Current', ...
            'FontSize', ...
            9, ...
            'FontWeight', ...
            'bold', ...
            'Color', ...
            Colours.text);
        %% ----------------------------------------------------
        % MAXIMUM VALID DOWNFORCE POINT
        %
        % This is explicitly the maximum VALID downforce found
        % within the TESTED grid.
        %
        % It is NOT being described as an optimised setup.
        % -----------------------------------------------------
        if isfield(Study,'maxDownforceFrontSpring') && ...
                isfield(Study,'maxDownforceRearSpring') && ...
                isfinite(Study.maxDownforceFrontSpring) && ...
                isfinite(Study.maxDownforceRearSpring)
            plot( ...
                analysisAxes, ...
                Study.maxDownforceFrontSpring, ...
                Study.maxDownforceRearSpring, ...
                'd', ...
                'MarkerSize', ...
                9, ...
                'LineWidth', ...
                1.8, ...
                'Color', ...
                Colours.pass);
            % Position label below marker so it does not
            % disappear against the upper plot boundary.
            text( ...
                analysisAxes, ...
                Study.maxDownforceFrontSpring + 3, ...
                Study.maxDownforceRearSpring - 5, ...
                'Max Valid DF', ...
                'FontSize', ...
                8, ...
                'FontWeight', ...
                'bold', ...
                'Color', ...
                Colours.pass);
        end
        %% ----------------------------------------------------
        % AXES FORMATTING
        % -----------------------------------------------------
        grid(analysisAxes,'on');
        box(analysisAxes,'on');
        analysisAxes.GridAlpha = ...
            0.18;
        analysisAxes.Layer = ...
            'top';
        xlim( ...
            analysisAxes, ...
            [min(frontSpringValues) ...
             max(frontSpringValues)]);
        ylim( ...
            analysisAxes, ...
            [min(rearSpringValues) ...
             max(rearSpringValues)]);
        xlabel( ...
            analysisAxes, ...
            'Front Spring Rate [N/mm]');
        ylabel( ...
            analysisAxes, ...
            'Rear Spring Rate [N/mm]');
        title( ...
            analysisAxes, ...
            sprintf( ...
            'Downforce & Aero-Platform Validity — %.0f km/h', ...
            currentSpeedKmh));
    end
