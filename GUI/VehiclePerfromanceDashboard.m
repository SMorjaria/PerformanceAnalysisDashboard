    function runAnalysis()
        try
            %% ------------------------------------------------
            % CURRENT SETUP
            % -------------------------------------------------
            CurrentSetup = Setup;
            CurrentOperating = Operating;
            CurrentSetup.springFront = ...
                frontSpringField.Value;
            CurrentSetup.springRear = ...
                rearSpringField.Value;
            CurrentSetup.arbFront = ...
                frontARBField.Value;
            CurrentSetup.arbRear = ...
                rearARBField.Value;
            CurrentSetup.rideHeightFront = ...
                frontRHField.Value;
            CurrentSetup.rideHeightRear = ...
                rearRHField.Value;
            CurrentOperating.speed = ...
                speedField.Value / 3.6;
            CurrentOperating.steerAngle = ...
                steerAngleField.Value;
            modelStateLabel.Text = ...
                'CALCULATING...';
            modelStateLabel.FontColor = ...
                Colours.warning;
            drawnow;
            %% ------------------------------------------------
            % CURRENT PERFORMANCE
            % -------------------------------------------------
            CurrentPerformance = ...
                evaluateVehiclePerformance( ...
                Vehicle, ...
                CurrentSetup, ...
                CurrentOperating, ...
                Tyre, ...
                Constants, ...
                AeroMap);
            %% ------------------------------------------------
            % BASELINE PERFORMANCE
            %
            % Evaluated at the SAME operating condition so that
            % the displayed deltas represent setup effects.
            % -------------------------------------------------
            BaselinePerformance = ...
                evaluateVehiclePerformance( ...
                Vehicle, ...
                BaselineSetup, ...
                CurrentOperating, ...
                Tyre, ...
                Constants, ...
                AeroMap);
            KPI = CurrentPerformance.KPI;
            Status = CurrentPerformance.Status;
            BaseKPI = BaselinePerformance.KPI;
            %% =================================================
            % PERFORMANCE VALUES
            % ==================================================
            downforceValue.Text = ...
                sprintf('%.1f N',KPI.downforce);
            efficiencyValue.Text = ...
                sprintf('%.3f',KPI.aeroEfficiency);
            aeroBalanceValue.Text = ...
                sprintf( ...
                '%.2f %%', ...
                KPI.aeroBalanceFrontPercent);
            lateralAccelValue.Text = ...
                sprintf( ...
                '%+.3f g', ...
                KPI.lateralAccelerationG);
            understeerValue.Text = ...
                sprintf( ...
                '%+.4f', ...
                KPI.understeerGradient);
            %% =================================================
            % PERFORMANCE DELTAS
            % ==================================================
            downforceDelta.Text = ...
                sprintf( ...
                '%+.1f N', ...
                KPI.downforce - ...
                BaseKPI.downforce);
            if abs(BaseKPI.aeroEfficiency) > eps
                efficiencyChangePercent = ...
                    100 * ...
                    (KPI.aeroEfficiency - ...
                    BaseKPI.aeroEfficiency) / ...
                    BaseKPI.aeroEfficiency;
            else
                efficiencyChangePercent = NaN;
            end
            efficiencyDelta.Text = ...
                sprintf( ...
                '%+.2f %%', ...
                efficiencyChangePercent);
            aeroBalanceDelta.Text = ...
                sprintf( ...
                '%+.2f %%', ...
                KPI.aeroBalanceFrontPercent - ...
                BaseKPI.aeroBalanceFrontPercent);
            lateralAccelDelta.Text = ...
                sprintf( ...
                '%+.4f g', ...
                KPI.lateralAccelerationG - ...
                BaseKPI.lateralAccelerationG);
            understeerDelta.Text = ...
                sprintf( ...
                '%+.4f', ...
                KPI.understeerGradient - ...
                BaseKPI.understeerGradient);
            %% =================================================
            % VEHICLE BALANCE CLASSIFICATION
            % ==================================================
            balanceTolerance = 0.002;
            if KPI.understeerGradient > balanceTolerance
                balanceValue.Text = ...
                    'UNDERSTEER';
                balanceValue.FontColor = ...
                    Colours.warning;
            elseif KPI.understeerGradient < -balanceTolerance
                balanceValue.Text = ...
                    'OVERSTEER';
                balanceValue.FontColor = ...
                    Colours.warning;
            else
                balanceValue.Text = ...
                    'NEAR NEUTRAL';
                balanceValue.FontColor = ...
                    Colours.pass;
            end
            %% =================================================
            % PLATFORM VALUES
            % ==================================================
            frontRHValue.Text = ...
                sprintf( ...
                '%.3f mm', ...
                KPI.frontRideHeight);
            rearRHValue.Text = ...
                sprintf( ...
                '%.3f mm', ...
                KPI.rearRideHeight);
            frontCompressionValue.Text = ...
                sprintf( ...
                '%.3f mm', ...
                KPI.frontCompression);
            rearCompressionValue.Text = ...
                sprintf( ...
                '%.3f mm', ...
                KPI.rearCompression);
            rakeValue.Text = ...
                sprintf( ...
                '%.4f deg', ...
                KPI.rakeAngleDeg);
            %% =================================================
            % PLATFORM DELTAS
            % ==================================================
            frontRHDelta.Text = ...
                sprintf( ...
                '%+.3f', ...
                KPI.frontRideHeight - ...
                BaseKPI.frontRideHeight);
            rearRHDelta.Text = ...
                sprintf( ...
                '%+.3f', ...
                KPI.rearRideHeight - ...
                BaseKPI.rearRideHeight);
            frontCompressionDelta.Text = ...
                sprintf( ...
                '%+.3f', ...
                KPI.frontCompression - ...
                BaseKPI.frontCompression);
            rearCompressionDelta.Text = ...
                sprintf( ...
                '%+.3f', ...
                KPI.rearCompression - ...
                BaseKPI.rearCompression);
            rakeDelta.Text = ...
                sprintf( ...
                '%+.4f', ...
                KPI.rakeAngleDeg - ...
                BaseKPI.rakeAngleDeg);
            %% =================================================
            % AERO-MAP MARGINS
            %
            % Validated Stage 4 map limits:
            %
            % Front RH >= 15 mm
            % Rear RH  >= 30 mm
            % ==================================================
            frontMinimumRH = 15;
            rearMinimumRH  = 30;
            frontMargin = ...
                KPI.frontRideHeight - ...
                frontMinimumRH;
            rearMargin = ...
                KPI.rearRideHeight - ...
                rearMinimumRH;
            frontMarginValue.Text = ...
                sprintf( ...
                '%+.3f mm', ...
                frontMargin);
            rearMarginValue.Text = ...
                sprintf( ...
                '%+.3f mm', ...
                rearMargin);
            setMarginColour( ...
                frontMarginValue, ...
                frontMargin);
            setMarginColour( ...
                rearMarginValue, ...
                rearMargin);
            %% =================================================
            % MODEL STATUS
            % ==================================================
            setStatus( ...
                aeroStatusValue, ...
                Status.aeroMapValid);
            setStatus( ...
                platformStatusValue, ...
                Status.platformConverged);
            setStatus( ...
                lateralStatusValue, ...
                Status.lateralSolverConverged);
            setStatus( ...
                verticalStatusValue, ...
                Status.verticalLoadValid);
            setStatus( ...
                overallStatusValue, ...
                Status.allValid);
            %% =================================================
            % ENGINEERING INTERPRETATION
            % ==================================================
            updateEngineeringInterpretation( ...
                KPI, ...
                BaseKPI, ...
                Status, ...
                BaselinePerformance.Status, ...
                CurrentOperating, ...
                frontMinimumRH, ...
                rearMinimumRH);
            %% =================================================
            % UPDATE TRADE-OFF MAP
            % ==================================================
            updateTradeoffMap( ...
                CurrentSetup, ...
                CurrentOperating);
            %% =================================================
            % OVERALL MODEL STATE
            % ==================================================
            if Status.allValid
                modelStateLabel.Text = ...
                    'MODEL STATUS: PASS';
                modelStateLabel.FontColor = ...
                    Colours.pass;
            else
                modelStateLabel.Text = ...
                    'MODEL STATUS: CHECK';
                modelStateLabel.FontColor = ...
                    Colours.warning;
            end
        catch ME
            modelStateLabel.Text = ...
                'MODEL ERROR';
            modelStateLabel.FontColor = ...
                Colours.fail;
            uialert( ...
                fig, ...
                ME.message, ...
                'Vehicle Model Error');
        end
    end
